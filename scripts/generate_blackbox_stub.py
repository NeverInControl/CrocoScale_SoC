#!/usr/bin/env python3
"""
scripts/generate_blackbox_stub.py
CrocoScale SoC — Automated Blackbox Stub Generator for Hardened Macros

Parses a structural/RTL Verilog or SystemVerilog module header (parameters and
ports) and generates a clean, synthesis/lint-ready `(* blackbox *)` stub model
with deterministic output tie-offs.

Defaults (when run without arguments):
  --input  : FABulousProject/CrocoScale_Fabric/Fabric/eFPGA_top.v
  --output : MACROS/FABulous/eFPGA_top.v

Usage:
  python3 scripts/generate_blackbox_stub.py
  python3 scripts/generate_blackbox_stub.py -i <src.v> -o <dst_blackbox.v>
"""

import re
import argparse
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//.*$", "", text, flags=re.MULTILINE)
    return text


def generate_blackbox_stub(src_path: Path, dst_path: Path):
    if not src_path.exists():
        raise FileNotFoundError(f"Source RTL file not found: {src_path}")

    raw_text = src_path.read_text(encoding="utf-8", errors="replace")
    clean_text = strip_comments(raw_text)

    # Match module header: module <name> #(...) (...); or module <name> (...);
    mod_match = re.search(
        r"\bmodule\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*(?:#\s*\((.*?)\))?\s*\((.*?)\)\s*;",
        clean_text,
        flags=re.DOTALL,
    )
    if not mod_match:
        raise ValueError(f"Could not parse ANSI module header in {src_path}")

    mod_name = mod_match.group(1)
    param_block = mod_match.group(2) or ""
    port_block = mod_match.group(3) or ""

    # Parse parameters
    params = []
    for pm in re.finditer(
        r"\bparameter\s+(?:(?:integer|int|signed|logic|reg|wire)\s+)?(?:\[[^\]]+\]\s*)?([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*([^,\n]+)",
        param_block,
    ):
        params.append((pm.group(1).strip(), pm.group(2).strip()))

    # Parse ports
    ports = []
    for line in port_block.splitlines():
        line_clean = line.strip().rstrip(",")
        if not line_clean:
            continue
        pm = re.match(
            r"^(input|output|inout)\s*(?:wire|reg|logic)?\s*(?:signed)?\s*(\[[^\]]+\])?\s*([a-zA-Z_][a-zA-Z0-9_]*)$",
            line_clean,
        )
        if pm:
            direction = pm.group(1)
            width_str = (pm.group(2) or "").strip()
            pname = pm.group(3).strip()
            ports.append((direction, width_str, pname))

    # Format output blackbox file
    lines = [
        "`timescale 1ns / 1ps",
        "",
        "/* ===============================================================================================",
        f" * Hard Macro Blackbox Model: {mod_name}",
        f" * Auto-generated by scripts/generate_blackbox_stub.py from {src_path.name}",
        " * =============================================================================================== */",
        "",
        "(* blackbox *)",
    ]

    if params:
        lines.append(f"module {mod_name} #(")
        max_plen = max(len(p[0]) for p in params)
        for i, (pname, pval) in enumerate(params):
            comma = "," if i < len(params) - 1 else ""
            lines.append(f"    parameter {pname.ljust(max_plen)} = {pval}{comma}")
        lines.append(") (")
    else:
        lines.append(f"module {mod_name} (")

    for i, (direction, width_str, pname) in enumerate(ports):
        comma = "," if i < len(ports) - 1 else ""
        dir_pad = direction.ljust(6)
        w_pad = width_str.ljust(8) if width_str else "        "
        lines.append(f"    {dir_pad} {w_pad} {pname}{comma}")
    lines.append(");")
    lines.append("")
    lines.append("    /* Stub default assignments for macro elaboration */")

    input_names = {pname for d, _, pname in ports if d == "input"}
    clk_port = "CLK" if "CLK" in input_names else ("clk_i" if "clk_i" in input_names else None)

    output_ports = [(w, p) for d, w, p in ports if d == "output"]
    max_olen = max((len(p) for _, p in output_ports), default=10)

    for width_str, pname in output_ports:
        # Preserve clock forwarding on user clock outputs (e.g. FAB_USER_CLK)
        if "USER_CLK" in pname and clk_port:
            m = re.match(r"\[\s*(\d+)\s*:\s*(\d+)\s*\]", width_str)
            if m:
                nbits = abs(int(m.group(1)) - int(m.group(2))) + 1
                rhs = f"{{{nbits}{{{clk_port}}}}}"
            else:
                rhs = clk_port
        elif pname == "clk_o" and clk_port:
            rhs = clk_port
        else:
            m = re.match(r"\[\s*(\d+)\s*:\s*(\d+)\s*\]", width_str)
            if m:
                nbits = abs(int(m.group(1)) - int(m.group(2))) + 1
                rhs = f"{nbits}'h0" if nbits > 3 else f"{nbits}'b{'0' * nbits}"
            elif width_str:
                rhs = "0"
            else:
                rhs = "1'b0"
        lines.append(f"    assign {pname.ljust(max_olen)} = {rhs};")

    lines.append("")
    lines.append("endmodule")
    lines.append("")

    dst_path.parent.mkdir(parents=True, exist_ok=True)
    dst_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"[SUCCESS] Generated blackbox stub '{mod_name}' ({len(params)} params, {len(ports)} ports) -> {dst_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Generate a (* blackbox *) Verilog stub from an RTL/structural module file."
    )
    parser.add_argument(
        "-i",
        "--input",
        type=Path,
        default=REPO_ROOT / "FABulousProject" / "CrocoScale_Fabric" / "Fabric" / "eFPGA_top.v",
        help="Input Verilog/SystemVerilog source file (default: FABulousProject/CrocoScale_Fabric/Fabric/eFPGA_top.v).",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=REPO_ROOT / "MACROS" / "FABulous" / "eFPGA_top.v",
        help="Output blackbox Verilog stub file (default: MACROS/FABulous/eFPGA_top.v).",
    )
    args = parser.parse_args()
    src = args.input if args.input.is_absolute() else REPO_ROOT / args.input
    dst = args.output if args.output.is_absolute() else REPO_ROOT / args.output
    generate_blackbox_stub(src, dst)


if __name__ == "__main__":
    main()

